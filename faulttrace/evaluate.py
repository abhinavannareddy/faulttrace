"""Evaluation on synthetic incidents.

Five checks, all on incidents generated by the same kind of model the diagnoser uses:
  1. ranking accuracy against two rule-based baselines,
  2. robustness when the real edge probabilities differ from the assumed ones,
  3. how far the verdicts of the full workflow can be trusted,
  4. detection of two simultaneous faults,
  5. what fleet failure rates are worth, if the customer has them.
"""
import copy
import json
import random
import sys
from pathlib import Path

from .agents import diagnose
from .diagnose import baseline_earliest_code, baseline_set_cover, rank_causes, rank_hypotheses, triage
from .model import load_vehicle, make_incident

VEHICLES = ["truck", "car", "bus", "excavator"]


def perturbed(v, rng, lo=0.6, hi=1.0):
    """Copy of the vehicle whose edge probabilities differ from what the diagnoser assumes."""
    w = copy.deepcopy(v)
    w._cache = {}
    for a, b in w.graph.edges:
        w.graph[a][b]["p"] = rng.uniform(lo, hi)
    return w


def run(n_per_vehicle: int = 200, seed: int = 11, mismatch: bool = False):
    out = {}
    for name in VEHICLES:
        v = load_vehicle(name)
        rng = random.Random(f"{seed}:{name}")
        truth = perturbed(v, rng) if mismatch else v
        stats = {"n": 0, "top1": 0, "top3": 0, "base": 0, "cover": 0,
                 "silent_n": 0, "silent_top1": 0, "silent_base": 0, "silent_cover": 0}
        for _ in range(n_per_vehicle):
            root = rng.choice(v.components)
            events = make_incident(truth, root, rng)
            if not events:
                continue
            burst = {c for c, _ in triage(v, events)["burst"]}
            ranking = rank_causes(v, burst)
            silent = root not in v.component_dtcs
            stats["n"] += 1
            stats["top1"] += ranking[0]["component"] == root
            stats["top3"] += root in [r["component"] for r in ranking[:3]]
            stats["base"] += baseline_earliest_code(v, events) == root
            stats["cover"] += baseline_set_cover(v, burst) == root
            if silent:
                stats["silent_n"] += 1
                stats["silent_top1"] += ranking[0]["component"] == root
                stats["silent_base"] += baseline_earliest_code(v, events) == root
                stats["silent_cover"] += baseline_set_cover(v, burst) == root
        out[name] = stats
    return out


def run_agent_check(n: int = 100, seed: int = 5):
    """Runs the full workflow on single-fault incidents and measures how far each verdict can be trusted.

    `correct` means the reported root cause is the true one; `in_group` means the true cause is the
    leader or one of the rivals named in an ambiguous report."""
    keys = ["verified", "ambiguous", "unverified"]
    res = {}
    for name in VEHICLES:
        v = load_vehicle(name)
        rng = random.Random(f"agent:{seed}:{name}")
        st = {"n": 0, "correct": 0, "plan_hit": 0}
        for k in keys:
            st[k] = st[f"{k}_correct"] = 0
        st["ambiguous_in_group"] = 0
        for _ in range(n):
            root = rng.choice(v.components)
            events = make_incident(v, root, rng)
            if not events:
                continue
            rep = diagnose(v, events)
            ok = rep.get("root_cause") == root
            st["n"] += 1
            st["correct"] += ok
            st["plan_hit"] += root in [r["component"] for r in rep.get("inspection_plan", [])[:2]]
            verdict = rep["verdict"]
            if verdict in keys:
                st[verdict] += 1
                st[f"{verdict}_correct"] += ok
                if verdict == "ambiguous":
                    group = {c for r in rep["ambiguity"]["rivals"] for c in r["components"]} | set(rep["root_causes"])
                    st["ambiguous_in_group"] += root in group
        res[name] = st
    return res


def run_multifault(n_per_vehicle: int = 250, seed: int = 8):
    """Half of the incidents have one root cause, half have two. Does the tool say 'two' when it is two?"""
    st = {"single_n": 0, "single_pair_claims": 0, "double_n": 0, "double_pair_claims": 0,
          "pair_claims_truly_double": 0, "pair_claims_exact": 0, "double_any_member": 0}
    for name in VEHICLES:
        v = load_vehicle(name)
        rng = random.Random(f"multi:{seed}:{name}")
        for i in range(n_per_vehicle):
            k = 1 if i % 2 == 0 else 2
            roots = rng.sample(v.components, k)
            events = make_incident(v, roots if k == 2 else roots[0], rng)
            burst = {c for c, _ in triage(v, events)["burst"]} if events else set()
            if not burst:
                continue
            lead = set(rank_hypotheses(v, burst)[0]["components"])
            if k == 1:
                st["single_n"] += 1
                st["single_pair_claims"] += len(lead) == 2
            else:
                st["double_n"] += 1
                st["double_any_member"] += bool(lead & set(roots))
                if len(lead) == 2:
                    st["double_pair_claims"] += 1
            if len(lead) == 2:
                st["pair_claims_truly_double"] += k == 2
                st["pair_claims_exact"] += lead == set(roots)
    return st


def with_failure_rates(v, rng):
    """Copy of the vehicle with made-up, uneven failure rates (log-normal), to test the value of priors."""
    w = copy.deepcopy(v)
    w._cache = {}
    for c in w.graph.nodes:
        w.graph.nodes[c]["failure_rate"] = rng.lognormvariate(0, 1.2)
    return w


def run_priors(n_per_vehicle: int = 300, seed: int = 4):
    """If the customer knows which components fail more often, how much does that help?

    Roots are drawn according to the failure rates. The same incidents are diagnosed with the rates
    (as a fleet operator would configure them) and without (uniform prior)."""
    st = {"n": 0, "with_priors": 0, "uniform": 0}
    for name in VEHICLES:
        v = with_failure_rates(load_vehicle(name), random.Random(f"rates:{seed}:{name}"))
        flat = copy.deepcopy(v)
        flat._cache = {}
        for c in flat.graph.nodes:
            flat.graph.nodes[c]["failure_rate"] = 1.0
        rng = random.Random(f"priors:{seed}:{name}")
        prior = v.prior()
        for _ in range(n_per_vehicle):
            root = rng.choices(v.components, weights=[prior[c] for c in v.components])[0]
            events = make_incident(v, root, rng)
            if not events:
                continue
            burst = {c for c, _ in triage(v, events)["burst"]}
            st["n"] += 1
            st["with_priors"] += rank_causes(v, burst)[0]["component"] == root
            st["uniform"] += rank_causes(flat, burst)[0]["component"] == root
    return st


def pct(a, b):
    return round(100 * a / b, 1) if b else None


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 200
    ev = run(n)
    mm = run(n, mismatch=True)
    ag = run_agent_check()
    mf = run_multifault()
    pr = run_priors()

    head = ("| Vehicle | Incidents | FaultTrace top-1 | FaultTrace top-3 | Set-cover rule | Earliest-code rule "
            "| Silent-root incidents | Silent: FaultTrace / set-cover / earliest |")
    lines = [head, "|---|---|---|---|---|---|---|---|"]
    tot = {k: 0 for k in ("n", "top1", "top3", "base", "cover", "silent_n", "silent_top1", "silent_base", "silent_cover")}

    def row(label, s):
        return (f"| {label} | {s['n']} | {pct(s['top1'], s['n'])}% | {pct(s['top3'], s['n'])}% | {pct(s['cover'], s['n'])}% | "
                f"{pct(s['base'], s['n'])}% | {s['silent_n']} | {pct(s['silent_top1'], s['silent_n'])}% / "
                f"{pct(s['silent_cover'], s['silent_n'])}% / {pct(s['silent_base'], s['silent_n'])}% |")

    for name, s in ev.items():
        for k in tot:
            tot[k] += s[k]
        lines.append(row(name, s))
    lines.append(row("**all**", tot))

    m = {k: sum(x[k] for x in mm.values()) for k in ("n", "top1", "top3", "base", "cover")}
    lines += ["", (f"Model mismatch (incidents generated with edge probabilities 0.6 to 1.0, diagnosed assuming 0.9; "
                  f"{m['n']} incidents): top-1 {pct(m['top1'], m['n'])}%, top-3 {pct(m['top3'], m['n'])}%, "
                  f"set-cover rule {pct(m['cover'], m['n'])}%, earliest-code rule {pct(m['base'], m['n'])}%.")]

    a = {k: sum(x[k] for x in ag.values()) for k in next(iter(ag.values()))}
    lines += ["", (f"Full workflow, {a['n']} single-fault incidents. Overall the reported root cause is correct "
                  f"{pct(a['correct'], a['n'])}% of the time; the true cause is in the top two of the inspection plan "
                  f"{pct(a['plan_hit'], a['n'])}%."),
              "",
              "| Verdict | Share of incidents | Root cause correct |", "|---|---|---|"]
    for k in ("verified", "ambiguous", "unverified"):
        lines.append(f"| {k} | {pct(a[k], a['n'])}% | {pct(a[f'{k}_correct'], a[k])}% |")
    lines.append("")
    lines.append(f"When the verdict is ambiguous, the true cause is the leader or a named rival "
                 f"{pct(a['ambiguous_in_group'], a['ambiguous'])}% of the time.")

    lines += ["", (f"Two simultaneous faults ({mf['single_n']} single-fault and {mf['double_n']} double-fault incidents): "
                  f"the tool claimed two faults in {mf['single_pair_claims'] + mf['double_pair_claims']} cases "
                  f"({pct(mf['pair_claims_truly_double'], mf['single_pair_claims'] + mf['double_pair_claims'])}% of those were "
                  f"truly double faults, {pct(mf['pair_claims_exact'], mf['single_pair_claims'] + mf['double_pair_claims'])}% named exactly "
                  f"the right pair), catching {pct(mf['double_pair_claims'], mf['double_n'])}% of the double faults. "
                  f"Even when it did not claim a pair, its leading answer contained a true cause in "
                  f"{pct(mf['double_any_member'], mf['double_n'])}% of double-fault incidents.")]

    lines += ["", (f"Fleet failure rates ({pr['n']} incidents, made-up uneven rates): top-1 {pct(pr['with_priors'], pr['n'])}% "
                  f"with the rates configured, {pct(pr['uniform'], pr['n'])}% with a uniform prior.")]

    text = "\n".join(lines)
    print(text)
    Path("results").mkdir(exist_ok=True)
    Path("results/latest.md").write_text(text + "\n")
    Path("results/latest.json").write_text(json.dumps(
        {"per_vehicle": ev, "mismatch": mm, "agent": ag, "multifault": mf, "priors": pr}, indent=2))


if __name__ == "__main__":
    main()
